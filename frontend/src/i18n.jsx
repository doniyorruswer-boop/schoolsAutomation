const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem('edumaktab_lang') || 'uz';
  });

  const changeLanguage = (newLang) => {
    setLang(newLang);
    localStorage.setItem('edumaktab_lang', newLang);
  };

  const t = (key, params = {}) => {
    let text = translations[lang]?.[key] || translations['uz']?.[key] || key;
    Object.keys(params).forEach(param => {
      text = text.replace(new RegExp(`\\{${param}\\}`, 'g'), params[param]);
    });
    return text;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang: changeLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
}
